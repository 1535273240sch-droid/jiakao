    private fun buildQuestions(): List<Question> {
        val out = mutableListOf<Question>()
        var seq = 1

        fun judgeSubject(subject: Int, pool: List<J>, chs: List<Chapter>, perChapter: Int) {
            repeat(pool.size) { i ->
                val item = pool[i]
                val chapter = chs[i % chs.size]
                out += makeQuestion(
                    seq++, subject, chapter, QType.JUDGE,
                    item.stem,
                    listOf(Option("A", "正确"), Option("B", "错误")),
                    listOf(if (item.yes) "A" else "B"),
                    item.explain,
                    tags = listOf(chapter.name.take(4), "判断"),
                )
            }
            // 用变体补足每章数量
            var k = 0
            while (out.count { it.subject == subject && it.type == QType.JUDGE } < pool.size.coerceAtLeast(perChapter * chs.size)) {
                val item = pool[k % pool.size]
                val chapter = chs[k % chs.size]
                out += makeQuestion(
                    seq++, subject, chapter, QType.JUDGE,
                    "【练习 ${k + 1}】${item.stem}",
                    listOf(Option("A", "正确"), Option("B", "错误")),
                    listOf(if (item.yes) "A" else "B"),
                    item.explain,
                    tags = listOf(chapter.name.take(4), "判断"),
                )
                k++
                if (k > 400) break
            }
        }
        fun fillSubject(subject: Int, judgePool: List<J>, singlePool: List<S>, multiPool: List<M>, chs: List<Chapter>, target: Int) {
            var k = 0
            while (out.count { it.subject == subject } < target) {
                val chapter = chs[k % chs.size]
                when (k % 5) {
                    0, 1 -> { // judge
                        val item = judgePool[k % judgePool.size]
                        out += makeQuestion(
                            seq++, subject, chapter, QType.JUDGE,
                            "${item.stem}",
                            listOf(Option("A", "正确"), Option("B", "错误")),
                            listOf(if (item.yes) "A" else "B"),
                            item.explain,
                            tags = listOf(chapter.name.take(4), "判断"),
                        )
                    }
                    2, 3 -> { // single
                        val item = singlePool[k % singlePool.size]
                        out += makeQuestion(
                            seq++, subject, chapter, QType.SINGLE,
                            item.stem,
                            item.opts.mapIndexed { idx, t -> Option(('A' + idx).toString(), t) },
                            listOf(('A' + item.correct).toString()),
                            item.explain,
                            tags = listOf(chapter.name.take(4), "单选"),
                        )
                    }
                    else -> { // multi
                        val item = multiPool[k % multiPool.size]
                        out += makeQuestion(
                            seq++, subject, chapter, QType.MULTI,
                            item.stem,
                            item.opts.mapIndexed { idx, t -> Option(('A' + idx).toString(), t) },
                            item.correct.map { ('A' + it).toString() }.sorted(),
                            item.explain,
                            tags = listOf(chapter.name.take(4), "多选"),
                        )
                    }
                }
                k++
                if (k > 1000) break
            }
        }

        // 科目一:目标 150 题(判定池直接铺,再补足)
        judgeSubject(1, S1_JUDGE, S1_CHAPTERS, perChapter = 6)
        fillSubject(1, S1_JUDGE, S1_SINGLE, S1_MULTI, S1_CHAPTERS, target = 150)
        // 科目四:目标 110 题
        fillSubject(4, S4_JUDGE, S4_SINGLE, S4_MULTI, S4_CHAPTERS, target = 110)

        return out
    }

    private fun makeQuestion(
        seq: Int,
        subject: Int,
        chapter: Chapter,
        type: QType,
        stem: String,
        options: List<Option>,
        answer: List<String>,
        explain: String,
        tags: List<String>,
    ): Question {
        val id = "s$subject-%06d".format(seq)
        val vehicles = when (seq % 5) {
            0 -> listOf("car", "truck")
            1 -> listOf("car", "bus")
            2 -> listOf("car", "moto")
            else -> listOf("car")
        }
        val media = mutableListOf<MediaRef>()
        if (seq % 3 == 0) {
            media += mediaRef(id, 1, MediaKind.IMAGE, if (seq % 2 == 0) 480 to 360 else 640 to 480)
        }
        if (seq % 7 == 0) {
            media += mediaRef(id, 2, MediaKind.ANIM, 640 to 360)
        }
        return Question(
            id = id,
            subject = subject,
            vehicles = vehicles,
            type = type,
            chapterId = chapter.id,
            tags = tags,
            stem = stem,
            options = options,
            answer = answer,
            explain = explain,
            media = media,
            rev = 1,
        )
    }

    /** 生成确定性的假 sha256(64 位十六进制)与字节数,内容寻址规则与合同一致 */
    private fun mediaRef(questionId: String, index: Int, kind: MediaKind, size: Pair<Int, Int>): MediaRef {
        val base = (questionId.hashCode().toLong() * 31 + index).let { "%016x".format(it) }
        val sha = base.repeat(4).take(64)
        val ext = if (kind == MediaKind.IMAGE || kind == MediaKind.ANIM) "webp" else "mp4"
        return MediaRef(
            sha256 = sha,
            ext = ext,
            kind = kind,
            width = size.first,
            height = size.second,
            bytes = 8_123L + (questionId.hashCode() and 0x3FFFF),
        )
    }
